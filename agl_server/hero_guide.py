    """按客户端 sc_12097 的三个列表返回指定角色的培养方案。"""
    guide = RECOMMENDATIONS.get(role_id, {})
    result = {}
    for category in ('astro', 'common_equip', 'omega_equip'):
        rows = guide.get(category, ())
        # 客户端按 rate 降序排列，将 floor(rate / 100) 显示为使用率。
